const dictionaries: Record<Language, Dictionary> = { en: en as unknown as Dictionary, vi };
const STORAGE_KEY = "eyeviz.playground.language";

function initialLanguage(): Language {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === "vi" || stored === "en") return stored;
  } catch {
    // Storage can be unavailable (privacy mode); fall back to the default.
  }
  return "vi";
}

let current: Language = initialLanguage();
const listeners = new Set<() => void>();

export function setLanguage(language: Language): void {
  current = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Not persisted; the choice still applies for this visit.
  }
  document.documentElement.lang = language;
  for (const listener of listeners) listener();
}

/** The current dictionary; re-renders when the language changes. */
export function useT(): Dictionary & { language: Language } {
  const language = useSyncExternalStore(
    (onChange) => {
      listeners.add(onChange);
      return () => listeners.delete(onChange);
    },
    () => current,
  );
  return { ...dictionaries[language], language };
}

export type T = ReturnType<typeof useT>;
